def classify_error(message: str) -> str:
    if message.startswith(VALIDATION_PREFIXES):
        return "VALIDATION_REJECT"
    return "CYCLE_ERROR"


def try_keep_display_awake(logger: DurableEventLogger) -> None:
    """Best-effort X11 screen-blanking disable; failure is logged for review."""
    commands = (
        ("xset", "s", "off"),
        ("xset", "s", "noblank"),
        ("xset", "-dpms"),
    )
    successes = 0
    details = []

    for command in commands:
        try:
            result = subprocess.run(
                command,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                text=True,
                timeout=3,
                check=False,
            )
            if result.returncode == 0:
                successes += 1
            else:
                details.append(
                    f"{' '.join(command)} returned {result.returncode}: "
                    f"{result.stderr.strip()}"
                )
        except Exception as exc:
            details.append(f"{' '.join(command)} failed: {exc}")

    if successes == len(commands):
        logger.write(
            "DISPLAY_KEEP_AWAKE",
            outcome="OK",
            detail="X11 screen blanking and DPMS disabled for benchmark.",
        )
    else:
        logger.write(
            "DISPLAY_KEEP_AWAKE",
            outcome="WARNING",
            detail=(
                f"{successes}/{len(commands)} xset commands succeeded. "
                + " | ".join(details)
            ),
        )


class BatteryBenchmarkGUI(object if SUMMARY_MODE else predict_ui.PredictionGUI):
    """Deployed PredictionGUI with unattended repetition and benchmark logging."""

    def __init__(self, root: tk.Tk, logger: DurableEventLogger, *, max_cycles: int = 0, cycle_timeout: float = 120.0):
        self.benchmark_logger = logger
        self.max_cycles = max_cycles
        self.cycle_timeout = cycle_timeout
        self._cycle_started_at = None
        self._watchdog_job = None
        self.exit_code = 0
        self.cycle_number = 0
        self.benchmark_running = False
        self._heartbeat_job = None
        super().__init__(root)
        self.root.protocol("WM_DELETE_WINDOW", self._manual_stop)

    def start_benchmark(self) -> None:
        """Perform final prechecks, define time zero, and start automated cycling."""
        if predict_ui.PREDICTION_IMPORT_ERROR is not None:
            self._fatal_stop(
                "Prediction dependencies are missing: "
                f"{predict_ui.PREDICTION_IMPORT_ERROR}"
            )
            return
        if self.sensor is None:
            self._fatal_stop("AS7265x sensor object was not created.")
            return
        try:
            if not self.sensor.is_connected():
                self._fatal_stop("AS7265x sensor is not connected.")
                return
        except Exception as exc:
            self._fatal_stop(f"Unable to verify AS7265x connection: {exc}")
            return
        if self.model is None:
            self._fatal_stop("Deployed model did not load.")
            return
        try:
            if self.predict_button.instate(["disabled"]):
                self._fatal_stop(
                    "Predict control is disabled after initialization. "
                    f"Status: {self.status_var.get()}"
                )
                return
        except Exception:
            # The explicit sensor/model checks above are the primary prechecks.
            pass

        # Make the deployed default LED condition explicit for the benchmark.
        self.led_white_var.set(True)
        self.led_ir_var.set(True)
        self.led_uv_var.set(True)

        self.benchmark_running = True
        self.benchmark_logger.begin_run()

        config = {
            "source_program": "predict_ui.py",
            "model_filename": predict_ui.MODEL_FILENAME,
            "model_class": type(self.model).__name__,
            "scan_count": predict_ui.SCAN_COUNT,
            "scan_delay_seconds": predict_ui.SCAN_DELAY_SECONDS,
            "led_settle_seconds": predict_ui.LED_SETTLE_SECONDS,
            "confidence_threshold": predict_ui.PREDICTION_CONFIDENCE_THRESHOLD,
            "sensor_integration_cycles": 50,
            "sensor_gain": "64x",
            "leds_enabled": ["White", "IR", "UV"],
            "sample_rotation_during_benchmark": False,
            "inter_cycle_delay_seconds": 0,
            "heartbeat_interval_seconds": HEARTBEAT_INTERVAL_SECONDS,
            "max_cycles": self.max_cycles,
            "cycle_timeout_seconds": self.cycle_timeout,
        }
        self.benchmark_logger.write(
            "RUN_START",
            outcome="OK",
            detail=json.dumps(config, separators=(",", ":")),
            include_health=True,
        )

        self.root.title("Corn Sweetness Prototype - Battery Runtime Benchmark")
        self.status_var.set(
            "BATTERY BENCHMARK ACTIVE - continuous automated prediction cycles"
        )

        # Write the first heartbeat immediately, then every 10 s thereafter.
        self._schedule_heartbeat()
        self.root.after_idle(self._begin_next_cycle)

    def _schedule_heartbeat(self) -> None:
        if not self.benchmark_running:
            return
        self.benchmark_logger.write(
            "HEARTBEAT",
            cycle=self.cycle_number if self.cycle_number else None,
            outcome="RUNNING",
            include_health=True,
        )
        self._heartbeat_job = self.root.after(
            int(HEARTBEAT_INTERVAL_SECONDS * 1000),
            self._schedule_heartbeat,
        )

    def _begin_next_cycle(self) -> None:
        if not self.benchmark_running:
            return
        if self.prediction_in_progress:
            self.root.after(100, self._begin_next_cycle)
            return
        if self.max_cycles > 0 and self.cycle_number >= self.max_cycles:
            self._normal_stop("Requested verification-cycle limit reached.")
            return

        self.cycle_number += 1
        self._cycle_started_at = time.monotonic()
        self._watchdog_job = self.root.after(1000, self._check_cycle_timeout)
        self.benchmark_logger.write(
            "CYCLE_START",
            cycle=self.cycle_number,
            outcome="STARTED",
        )

        # Reuse the deployed start_prediction() implementation exactly.
        super().start_prediction()

    def _check_cycle_timeout(self):
        if not self.benchmark_running or self._cycle_started_at is None:
            return
        duration = time.monotonic() - self._cycle_started_at
        if duration >= self.cycle_timeout:
            self.benchmark_running = False
            self.exit_code = 1
            self.benchmark_logger.write(
                "RUN_STOP", cycle=self.cycle_number, outcome="CYCLE_TIMEOUT",
                detail=f"Cycle exceeded {self.cycle_timeout:g} s (observed {duration:.1f} s). Run invalid for continuous-use battery runtime; sensor work may be stalled.",
            )
            print("BENCHMARK INVALID: prediction timed out. Check sensor and logs.", file=sys.stderr)
            # Do not start another worker or touch I2C concurrently with a stuck
            # worker. Exit the GUI; this does not guarantee sensor LEDs turn off.
            self.root.destroy()
            return
        self._watchdog_job = self.root.after(1000, self._check_cycle_timeout)

    def _complete_cycle_timer(self):
        self._cycle_started_at = None
        if self._watchdog_job is not None:
            self.root.after_cancel(self._watchdog_job)
            self._watchdog_job = None

    def _finish_prediction_success(
        self,
        predicted_label,
        confidence_text,
        capture_text,
        averaged_scan,
        led_flags,
    ):
        if not self.benchmark_running:
            return
        self._complete_cycle_timer()
        # Preserve deployed behavior, including GUI update and history writing.
        super()._finish_prediction_success(
            predicted_label,
            confidence_text,
            capture_text,
            averaged_scan,
            led_flags,
        )
        self.benchmark_logger.write(
            "CYCLE_END",
            cycle=self.cycle_number,
            outcome="SUCCESS",
            detail=f"{predicted_label} | {confidence_text}",
        )
        if self.benchmark_running:
            self.root.after_idle(self._begin_next_cycle)

    def _finish_prediction_error(self, error_message):
        """
        Non-blocking replacement for the deployed modal error dialog.

        The acquisition/validation path is unchanged. Only the modal message box
        is suppressed so a validation rejection or recoverable error cannot halt
        an unattended battery test.
        """
        if not self.benchmark_running:
            return
        self._complete_cycle_timer()
        self.progress_var.set(0)
        self.countdown_var.set("")
        self.measurement_var.set("")
        self.prediction_in_progress = False
        self._set_controls_state("normal")

        outcome = classify_error(str(error_message))
        self.result_var.set(f"Benchmark cycle result: {outcome}")
        self.status_var.set(str(error_message))
        self.benchmark_logger.write(
            "CYCLE_END",
            cycle=self.cycle_number,
            outcome=outcome,
            detail=str(error_message),
        )

        if self.benchmark_running:
            # Validation rejection is part of the normal deployed decision path
            # and receives no artificial inter-cycle delay. A non-validation
            # software/hardware error receives a short retry delay to prevent an
            # abnormal tight error loop from dominating the workload.
            retry_ms = (
                0
                if outcome == "VALIDATION_REJECT"
                else int(predict_ui.SCAN_DELAY_SECONDS * 1000)
            )
            self.root.after(retry_ms, self._begin_next_cycle)

    def _normal_stop(self, reason: str) -> None:
        if not self.benchmark_running:
            return
        self.benchmark_running = False
        self.benchmark_logger.write(
            "RUN_STOP",
            cycle=self.cycle_number if self.cycle_number else None,
            outcome="CONTROLLED_STOP",
            detail=reason,
            include_health=True,
        )
        self.status_var.set(f"Battery benchmark stopped: {reason}")
        self.root.after(250, self.root.destroy)

    def _manual_stop(self) -> None:
        if self.benchmark_running:
            self.benchmark_running = False
            self.benchmark_logger.write(
                "RUN_STOP",
                cycle=self.cycle_number if self.cycle_number else None,
                outcome="MANUAL_STOP",
                detail="Benchmark window was closed manually.",
                include_health=True,
            )
        self.root.destroy()

    def _fatal_stop(self, reason: str) -> None:
        self.benchmark_running = False
        self.benchmark_logger.write(
            "RUN_STOP",
            cycle=self.cycle_number if self.cycle_number else None,
            outcome="FATAL_PRECHECK",
            detail=reason,
            include_health=True,
        )
        self.status_var.set(f"Battery benchmark could not start: {reason}")
        print(f"FATAL: {reason}", file=sys.stderr)


