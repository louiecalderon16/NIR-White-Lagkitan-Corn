def main() -> int:
    args = parse_args()
    base_dir = Path(__file__).resolve().parent
    log_dir = base_dir / LOG_DIR_NAME

    if args.summary or args.summary_latest:
        target = args.summary if args.summary else newest_runtime_log(log_dir)
        if target is None:
            print(f"No battery runtime logs found in {log_dir}", file=sys.stderr)
            return 1
        return summarize_log(target)

    if not math.isfinite(args.cycle_timeout) or args.cycle_timeout <= 0:
        print("--cycle-timeout must be a finite positive number.", file=sys.stderr)
        return 2

    if args.cycles < 0:
        print("--cycles must be 0 or a positive integer.", file=sys.stderr)
        return 2

    official_mode = args.cycles == 0
    official_confirmed = False
    if official_mode:
        official_confirmed = confirm_official_start()
        if not official_confirmed:
            print("Official benchmark not started; start conditions were not confirmed.")
            return 2

    run_id = datetime.now().astimezone().strftime("%Y%m%d_%H%M%S")
    log_dir.mkdir(parents=True, exist_ok=True)

    runtime_log = log_dir / f"battery_runtime_{run_id}.csv"
    benchmark_history = log_dir / f"battery_prediction_history_{run_id}.csv"
    metadata_path = log_dir / f"battery_runtime_{run_id}_metadata.json"

    logger = DurableEventLogger(runtime_log)

    # Keep hundreds of benchmark-generated predictions out of the prototype's
    # normal prediction_history.csv.
    predict_ui.HISTORY_PATH = str(benchmark_history)

    metadata = build_metadata(
        run_id=run_id,
        runtime_log=runtime_log,
        benchmark_history=benchmark_history,
        requested_cycle_limit=args.cycles,
        official_conditions_confirmed=official_confirmed,
    )
    metadata["cycle_timeout_seconds"] = args.cycle_timeout
    metadata["timed_interval"] = "RUN_START to last complete event; battery endpoint requires external confirmation"
    durable_write_text(
        metadata_path,
        json.dumps(metadata, indent=2, ensure_ascii=False) + "\n",
    )

    print("Battery runtime benchmark")
    print(f"Runtime log: {runtime_log}")
    print(f"Benchmark prediction history: {benchmark_history}")
    print(f"Metadata: {metadata_path}")
    if official_mode:
        print("Mode: OFFICIAL CONTINUOUS RUNDOWN - expected endpoint is battery power loss")
    else:
        print(f"Mode: VERIFICATION - stop after {args.cycles} cycles")

    root = tk.Tk()
    try:
        app = BatteryBenchmarkGUI(root, logger, max_cycles=args.cycles, cycle_timeout=args.cycle_timeout)
    except Exception as exc:
        logger.write(
            "RUN_STOP",
            outcome="FATAL_INITIALIZATION",
            detail=f"{type(exc).__name__}: {exc}",
            include_health=True,
        )
        raise

    # Perform this before RUN_START so display setup is not part of the timed
    # continuous workload interval. Its success/failure remains in the log.
    try_keep_display_awake(logger)

    # Begin only after Tk has finished constructing the deployed GUI.
    root.after_idle(app.start_benchmark)

    try:
        root.mainloop()
    except KeyboardInterrupt:
        app._manual_stop()

    return app.exit_code


if __name__ == "__main__":
    raise SystemExit(main())
