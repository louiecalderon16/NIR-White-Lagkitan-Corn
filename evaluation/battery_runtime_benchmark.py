def read_cpu_temperature_c() -> Optional[float]:
    """Read SoC temperature, preferring Linux thermal sysfs."""
    thermal_path = Path("/sys/class/thermal/thermal_zone0/temp")
    try:
        raw = float(thermal_path.read_text(encoding="utf-8").strip())
        # Raspberry Pi Linux thermal sysfs normally reports millidegrees C.
        return raw / 1000.0 if raw > 1000.0 else raw
    except (OSError, ValueError):
        pass

    # Fallback for Raspberry Pi OS systems with vcgencmd available.
    try:
        result = subprocess.run(
            ["vcgencmd", "measure_temp"],
            capture_output=True,
            text=True,
            timeout=1,
            check=False,
        )
        if result.returncode != 0:
            return None
        match = re.search(r"temp=([+-]?[0-9]+(?:\.[0-9]+)?)", result.stdout)
        return float(match.group(1)) if match else None
    except (OSError, subprocess.SubprocessError, ValueError):
        return None


def read_throttled_mask() -> Tuple[Optional[int], str]:
    """Read Raspberry Pi vcgencmd get_throttled bit mask."""
    try:
        result = subprocess.run(
            ["vcgencmd", "get_throttled"],
            capture_output=True,
            text=True,
            timeout=1,
            check=False,
        )
        if result.returncode != 0:
            return None, ""
        match = re.search(r"throttled=(0x[0-9a-fA-F]+)", result.stdout.strip())
        if not match:
            return None, ""
        return int(match.group(1), 16), match.group(1).lower()
    except (OSError, subprocess.SubprocessError, ValueError):
        return None, ""


def decode_throttled_mask(mask: Optional[int]) -> Dict[str, str]:
    decoded = {name: "" for name in THROTTLED_BITS.values()}
    if mask is None:
        return decoded
    for bit, name in THROTTLED_BITS.items():
        decoded[name] = "1" if mask & (1 << bit) else "0"
    return decoded


def read_pi_health() -> Dict[str, str]:
    temp = read_cpu_temperature_c()
    mask, raw_hex = read_throttled_mask()
    health = {
        "cpu_temp_c": "" if temp is None else f"{temp:.3f}",
        "throttled_hex": raw_hex,
    }
    health.update(decode_throttled_mask(mask))
    return health


