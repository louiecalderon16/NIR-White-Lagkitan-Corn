def local_timestamp() -> str:
    """Return a timezone-aware local ISO-8601 timestamp."""
    return datetime.now().astimezone().isoformat(timespec="milliseconds")


def system_uptime_seconds() -> Optional[float]:
    """Return Linux system uptime, or None if unavailable."""
    try:
        with open("/proc/uptime", "r", encoding="utf-8") as handle:
            return float(handle.read().split()[0])
    except (OSError, ValueError, IndexError):
        return None


def fsync_directory(directory: Path) -> None:
    """Best-effort sync of a directory entry after creating benchmark files."""
    try:
        fd = os.open(str(directory), os.O_RDONLY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    except OSError:
        # File contents are still explicitly fsynced. Directory fsync is an
        # additional Linux durability measure and should not abort the test.
        pass


def durable_write_text(path: Path, text: str) -> None:
    """Write a small text file and request that it be committed to storage."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())
    fsync_directory(path.parent)


def file_sha256(path: Path) -> Optional[str]:
    """Return SHA-256 for a file, or None when the file cannot be read."""
    try:
        digest = hashlib.sha256()
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
        return digest.hexdigest()
    except OSError:
        return None


def read_text_file(path: Path) -> Optional[str]:
    try:
        return path.read_text(encoding="utf-8", errors="replace").strip("\x00\n ")
    except OSError:
        return None


def raspberry_pi_model() -> Optional[str]:
    return read_text_file(Path("/proc/device-tree/model"))


def os_pretty_name() -> Optional[str]:
    try:
        values = {}
        with open("/etc/os-release", "r", encoding="utf-8") as handle:
            for line in handle:
                if "=" not in line:
                    continue
                key, value = line.rstrip().split("=", 1)
                values[key] = value.strip().strip('"')
        return values.get("PRETTY_NAME")
    except OSError:
        return None


def package_version(distribution_name: str) -> Optional[str]:
    try:
        return importlib.metadata.version(distribution_name)
    except importlib.metadata.PackageNotFoundError:
        return None


def read_backlight_state() -> list:
    """Capture software-visible backlight state when the display exposes it."""
    states = []
    root = Path("/sys/class/backlight")
    try:
        devices = sorted(root.iterdir())
    except OSError:
        return states

    for device in devices:
        entry = {"device": device.name}
        for name in ("brightness", "actual_brightness", "max_brightness", "bl_power"):
            value = read_text_file(device / name)
            if value is not None:
                entry[name] = value
        states.append(entry)
    return states


