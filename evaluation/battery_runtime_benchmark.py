class DurableEventLogger:
    """Append-only CSV logger; every record is flushed and fsynced."""

    FIELDNAMES = (
        "timestamp",
        "elapsed_s",
        "system_uptime_s",
        "cycle",
        "event",
        "outcome",
        "cpu_temp_c",
        "throttled_hex",
        "undervoltage_now",
        "arm_freq_capped_now",
        "throttled_now",
        "soft_temp_limit_now",
        "undervoltage_occurred",
        "arm_freq_capped_occurred",
        "throttling_occurred",
        "soft_temp_limit_occurred",
        "detail",
    )

    def __init__(self, path: Path):
        self.path = path
        self._lock = threading.Lock()
        self._run_start_monotonic: Optional[float] = None
        path.parent.mkdir(parents=True, exist_ok=True)

        with path.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=self.FIELDNAMES)
            writer.writeheader()
            handle.flush()
            os.fsync(handle.fileno())
        fsync_directory(path.parent)

    def begin_run(self) -> None:
        """Set the elapsed-time origin immediately before RUN_START is logged."""
        self._run_start_monotonic = time.monotonic()

    def write(
        self,
        event: str,
        *,
        cycle: Optional[int] = None,
        outcome: str = "",
        detail: str = "",
        include_health: bool = False,
    ) -> None:
        now_monotonic = time.monotonic()
        elapsed = (
            None
            if self._run_start_monotonic is None
            else now_monotonic - self._run_start_monotonic
        )
        uptime = system_uptime_seconds()
        health = read_pi_health() if include_health else {
            "cpu_temp_c": "",
            "throttled_hex": "",
            **{name: "" for name in THROTTLED_BITS.values()},
        }

        row = {
            "timestamp": local_timestamp(),
            "elapsed_s": "" if elapsed is None else f"{elapsed:.3f}",
            "system_uptime_s": "" if uptime is None else f"{uptime:.3f}",
            "cycle": "" if cycle is None else cycle,
            "event": event,
            "outcome": outcome,
            **health,
            "detail": str(detail).replace("\r", " ").replace("\n", " "),
        }

        with self._lock:
            with self.path.open("a", newline="", encoding="utf-8") as handle:
                writer = csv.DictWriter(handle, fieldnames=self.FIELDNAMES)
                writer.writerow(row)
                handle.flush()
                os.fsync(handle.fileno())


