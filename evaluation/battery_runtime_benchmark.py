def confirm_official_start() -> bool:
    print()
    print("OFFICIAL BATTERY RUNDOWN - START CONDITION CHECK")
    print("Confirm ALL of the following before starting:")
    print("  1. IP5353 charge indication reached four steady white LEDs while charging.")
    print("  2. Charger is now disconnected from the prototype.")
    print("  3. Final prototype hardware/peripherals are connected and the display is ON.")
    print("  4. A white Lagkitan corn sample is positioned at the sensor and will remain stationary.")
    print("  5. Display setting will not be changed and there will be no user interaction after start.")
    print()
    response = input("Type START to confirm these conditions and begin: ").strip()
    return response == "START"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Automated continuous-use battery runtime benchmark."
    )
    parser.add_argument(
        "--cycles",
        type=int,
        default=0,
        help="Stop after N cycles. Default 0 = run until power loss.",
    )
    parser.add_argument("--cycle-timeout", type=float, default=120.0,
                        help="Maximum seconds per prediction before invalidating and stopping the run (default: 120).")
    parser.add_argument(
        "--summary",
        type=Path,
        help="Summarize one existing battery-runtime CSV log.",
    )
    parser.add_argument(
        "--summary-latest",
        action="store_true",
        help="Summarize the newest battery-runtime CSV log.",
    )
    return parser.parse_args()


