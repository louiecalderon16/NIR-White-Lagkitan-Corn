def newest_runtime_log(log_dir: Path) -> Optional[Path]:
    logs = sorted(
        log_dir.glob("battery_runtime_*.csv"),
        key=lambda path: path.stat().st_mtime,
        reverse=True,
    )
    return logs[0] if logs else None


def parse_float(value: str) -> Optional[float]:
    try:
        number = float(value)
        return number if math.isfinite(number) else None
    except (TypeError, ValueError):
        return None


def parse_hex_mask(value: str) -> Optional[int]:
    try:
        return int(value, 16) if value else None
    except (TypeError, ValueError):
        return None


def summarize_log(path: Path) -> int:
    if not path.is_file():
        print(f"Log not found: {path}", file=sys.stderr)
        return 1

    rows = []
    # Detail fields are single-line JSON/status messages. Ignore incomplete
    # trailing physical lines and malformed rows after abrupt interruption.
    discarded = 0
    with path.open("r", newline="", encoding="utf-8", errors="replace") as handle:
        header = handle.readline()
        fieldnames = next(csv.reader([header]), [])
        if fieldnames != list(DurableEventLogger.FIELDNAMES):
            print("Unexpected runtime log header.", file=sys.stderr)
            return 1
        for line in handle:
            try:
                values = next(csv.reader([line], strict=True))
                if not line.endswith("\n") or len(values) != len(fieldnames):
                    raise ValueError("Incomplete row")
                row = dict(zip(fieldnames, values))
                elapsed = parse_float(row.get("elapsed_s", ""))
                if not row["elapsed_s"]:
                    continue
                if elapsed is None or elapsed < 0 or row["event"] not in {
                    "RUN_START", "HEARTBEAT", "CYCLE_START", "CYCLE_END", "RUN_STOP"
                } or not row["outcome"]:
                    raise ValueError("Invalid timed row")
                datetime.fromisoformat(row["timestamp"])
                row["_elapsed"] = elapsed
                rows.append(row)
            except (ValueError, csv.Error, StopIteration):
                discarded += 1

    if not rows:
        print(f"No timed benchmark records found in {path}", file=sys.stderr)
        return 1

    starts = [row for row in rows if row.get("event") == "RUN_START"]
    heartbeats = [row for row in rows if row.get("event") == "HEARTBEAT"]
    cycle_starts = [row for row in rows if row.get("event") == "CYCLE_START"]
    cycle_ends = [row for row in rows if row.get("event") == "CYCLE_END"]
    stops = [row for row in rows if row.get("event") == "RUN_STOP"]

    # Latest complete record proves only that the logger reached that time.
    # It does not prove ongoing predictions or the cause/time of power loss.
    endpoint = max(rows, key=lambda row: row["_elapsed"])
    elapsed_s = endpoint["_elapsed"]
    hours = int(elapsed_s // 3600)
    minutes = int((elapsed_s % 3600) // 60)
    seconds = elapsed_s % 60

    success = sum(row.get("outcome") == "SUCCESS" for row in cycle_ends)
    rejected = sum(row.get("outcome") == "VALIDATION_REJECT" for row in cycle_ends)
    errors = sum(row.get("outcome") == "CYCLE_ERROR" for row in cycle_ends)

    # Cycle-duration consistency.
    start_by_cycle = {
        row.get("cycle"): row["_elapsed"]
        for row in cycle_starts
        if row.get("cycle")
    }
    cycle_durations = []
    for row in cycle_ends:
        cycle = row.get("cycle")
        if cycle in start_by_cycle:
            duration = row["_elapsed"] - start_by_cycle[cycle]
            if duration >= 0:
                cycle_durations.append(duration)

    # Thermal diagnostics from RUN_START/heartbeats/stops with health data.
    temperatures = []
    masks = []
    for row in rows:
        temp = parse_float(row.get("cpu_temp_c", ""))
        if temp is not None:
            temperatures.append(temp)
        mask = parse_hex_mask(row.get("throttled_hex", ""))
        if mask is not None:
            masks.append((row, mask))

    start_mask = None
    if starts:
        start_mask = parse_hex_mask(starts[0].get("throttled_hex", ""))
    final_mask = masks[-1][1] if masks else None

    any_current_undervoltage = any(mask & (1 << 0) for _, mask in masks)
    any_current_capping = any(mask & (1 << 1) for _, mask in masks)
    any_current_throttling = any(mask & (1 << 2) for _, mask in masks)
    any_current_soft_temp = any(mask & (1 << 3) for _, mask in masks)

    new_sticky = []
    if start_mask is not None and final_mask is not None:
        for bit in STICKY_THROTTLED_BITS:
            if (final_mask & (1 << bit)) and not (start_mask & (1 << bit)):
                new_sticky.append(THROTTLED_BITS[bit])

    print(f"Log: {path}")
    if starts:
        print(f"Run start: {starts[0]['timestamp']}")
    print(f"Last durable event: {endpoint['timestamp']} ({endpoint['event']})")
    print(
        "Elapsed time to last complete event (not verified battery runtime): "
        f"{hours} h {minutes} min {seconds:.1f} s"
    )
    print(
        f"Completed cycles: {len(cycle_ends)} "
        f"(success={success}, validation_reject={rejected}, errors={errors})"
    )

    print(f"Discarded malformed/incomplete rows: {discarded}")
    if errors or rejected:
        print("Workload warning: rejected/error cycles occurred; review their frequency and timing.")
    if len(heartbeats) > 1:
        gaps = [b["_elapsed"] - a["_elapsed"] for a, b in zip(heartbeats, heartbeats[1:])]
        print(f"Largest observed heartbeat gap: {max(gaps):.3f} s (does not bound final gap)")

    if cycle_durations:
        print(
            "Completed-cycle duration: "
            f"mean={fmean(cycle_durations):.3f} s, "
            f"min={min(cycle_durations):.3f} s, "
            f"max={max(cycle_durations):.3f} s"
        )

    successful_rows = [row for row in cycle_ends if row.get("outcome") == "SUCCESS"]
    if successful_rows:
        last_success = successful_rows[-1]
        print(
            "Last successful prediction cycle: "
            f"{last_success.get('cycle', '')} at {last_success['_elapsed']:.1f} s"
        )

    if temperatures:
        print(
            "CPU temperature during logged health samples: "
            f"mean={fmean(temperatures):.2f} C, "
            f"min={min(temperatures):.2f} C, "
            f"max={max(temperatures):.2f} C"
        )
    else:
        print("CPU temperature: unavailable")

    if masks:
        print(
            "Raspberry Pi health flags observed during benchmark: "
            f"undervoltage_now={'YES' if any_current_undervoltage else 'no'}, "
            f"frequency_capped_now={'YES' if any_current_capping else 'no'}, "
            f"throttled_now={'YES' if any_current_throttling else 'no'}, "
            f"soft_temp_limit_now={'YES' if any_current_soft_temp else 'no'}"
        )
        if start_mask is not None:
            print(f"get_throttled at run start: 0x{start_mask:x}")
        if final_mask is not None:
            print(f"get_throttled at last health sample: 0x{final_mask:x}")
        print(
            "New sticky health flags since run start: "
            + (", ".join(new_sticky) if new_sticky else "none detected")
        )
    else:
        print("Raspberry Pi vcgencmd throttling telemetry: unavailable")

    if stops:
        last_stop = stops[-1]
        print(
            f"Controlled stop recorded: {last_stop.get('outcome', '')} - "
            f"{last_stop.get('detail', '')}"
        )
        print("Endpoint type: recorded software stop")
        if last_stop.get("outcome") == "CYCLE_TIMEOUT":
            print("RUN INVALID: prediction stalled; elapsed time is not continuous-use battery runtime.")
    else:
        print("Endpoint type: uncontrolled termination; cause unconfirmed.")
        print("No RUN_STOP record: power loss, application crash, or a freeze are possible.")
        print("Final unobserved interval is unknown; the nominal heartbeat interval is not an error bound.")
        print("Confirm battery power loss independently before reporting a battery rundown result.")
    if not successful_rows:
        print("RUN NOT VALIDATED: no successful prediction cycles recorded.")

    return 0


